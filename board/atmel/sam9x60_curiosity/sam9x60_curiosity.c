static const uint8_t oled_init_cmds[] = {
    0xAE, // Display OFF
    0xD5, 0x80, // Set Display Clock Divide Ratio
    0xA8, 0x3F, // Set Multiplex Ratio
    0xD3, 0x00, // Set Display Offset
    0x40, // Set Display Start Line
    0x8D, 0x14, // Enable Charge Pump
    0x20, 0x00, // Memory Addressing Mode: Horizontal
    0xA1, // Segment Re-map
    0xC8, // COM Output Scan Direction
    0xDA, 0x12, // COM Pins Hardware Configuration
    0x81, 0xCF, // Set Contrast Control
    0xD9, 0xF1, // Set Pre-charge Period
    0xDB, 0x40, // Set VCOMH Deselect Level
    0xA4, // Disable Entire Display On
    0xA6, // Set Normal Display Mode
    0xAF  // Display ON
};

static int oled_splash(void) {
    struct udevice *bus;
    int ret = uclass_get_device_by_seq(UCLASS_I2C, 0, &bus);
    if (ret) {
        printf("Failed to get I2C bus 0\n");
        return ret;
    }
    printf("Success to set I2C bus 0\n");
    struct udevice *oled_dev = NULL;
    ret = dm_i2c_probe(bus, 0x3C, 0, &oled_dev);
    if (ret) {
        printf("Failed to probe I2C OLED at 0x3C\n");
        return ret;
    }
    printf("Success to probe OLED device 0x3C\n");
    for (int i = 0; i < sizeof(oled_init_cmds); i++) {
        ret = dm_i2c_write(oled_dev, 0x00, &oled_init_cmds[i], 1);
        if (ret) {
            printf("OLED init failed: %d : 0x%02X\n", i, oled_init_cmds[i]);
            return ret;
        }
    }
    // calc offset
	uint8_t oled_first_byte = 0;
	dm_i2c_read(oled_dev, 0x00, &oled_first_byte, 1);
    printf("OLED Initialized! 0x%02X\n", oled_first_byte);
    uint8_t offset = (oled_first_byte == 0x28) ? 2 : 0;
    // draw logo
	for (int page = 0; page < 8; page++) {
        uint8_t cmd[] = {0xB0 + page, offset, 0x10};
        ret = dm_i2c_write(oled_dev, 0x00, cmd, sizeof(cmd));
        if (ret) {
            printf("OLED page command fail: %d\n", page);
            return ret;
        }
        ret = dm_i2c_write(oled_dev, 0x40, &logo[page*128], 128);
        if (ret) {
            printf("OLED page data fail: %d\n", page);
            return ret;
        } 
    }
    printf("OLED Splash Done\n");
    return 0;
}

static void board_leds_init(void)
{
#if CONFIG_IS_ENABLED(LED)
	const char *led_name;
	struct udevice *dev;
	int ret;

	led_name = ofnode_conf_read_str("u-boot,boot-led");
	if (!led_name)
		return;

	ret = led_get_by_label(led_name, &dev);
	if (ret)
		return;

	led_set_state(dev, LEDST_ON);
#else
	at91_set_pio_output(AT91_PIO_PORTD, 17, 0);	/* LED RED */
	at91_set_pio_output(AT91_PIO_PORTD, 19, 0);	/* LED GREEN */
	at91_set_pio_output(AT91_PIO_PORTD, 21, 1);	/* LED BLUE */
#endif
}

